/* Subtitle delay regression tests: positive=late, negative=early. */
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const api = require("../subtitle-sync.js");
const html = fs.readFileSync(path.join(__dirname,"../index.html"),"utf8");
const player = fs.readFileSync(path.join(__dirname,"../player.js"),"utf8");
new Function(player);
assert.equal(api.clampDelay(1.13),1.25);
assert.equal(api.clampDelay(-1.13),-1.25);
assert.equal(api.clampDelay(44),30);
assert.equal(api.clampDelay(-44),-30);
assert.equal(api.clampDelay(NaN),0);
assert.equal(api.displayDelay(0),"0.00 s");
assert.equal(api.displayDelay(0.25),"+0.25 s");
assert.equal(api.displayDelay(-0.5,"ru"),"−0.50 с");
assert.equal(api.shiftedTime(12,0.5),11.5);
assert.equal(api.shiftedTime(12,-0.5),12.5);
const cues=[{startTime:2,endTime:4},{startTime:5,endTime:6}];
const track={cues};
assert.equal(api.shiftTextTrack(track,0.5),2);
assert.deepEqual(cues.map(c=>[c.startTime,c.endTime]),[[2.5,4.5],[5.5,6.5]]);
api.shiftTextTrack(track,-0.25);
assert.deepEqual(cues.map(c=>[c.startTime,c.endTime]),[[1.75,3.75],[4.75,5.75]]);
api.shiftTextTrack(track,0);
assert.deepEqual(cues.map(c=>[c.startTime,c.endTime]),[[2,4],[5,6]]);
api.shiftTextTrack(track,-30);
assert.equal(cues[0].startTime,0);
assert.ok(cues[0].endTime>0);
assert.match(html,/id="subtitleDelayEarlier"/);
assert.match(html,/id="subtitleDelayLater"/);
assert.match(html,/id="subtitleDelayReset"/);
assert.match(player,/media\.currentTime - subtitleDelayForCurrent\(\)/);
assert.match(player,/sync\.shiftTextTrack/);
assert.match(player,/store\.subtitleDelays/);
console.log("PASS: subtitle sync cues, bitmap timing, limits, and controls");
